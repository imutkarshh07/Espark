export const ALL_NCERT_CHAPTERS: Record<string, NcertChapter[]> = {
  Physics: NCERT_PHYSICS,
  Chemistry: NCERT_CHEMISTRY,
  Biology: NCERT_BIOLOGY,
  Mathematics: NCERT_MATHEMATICS,
};

export const normalizeSubjectName = (sub: string): 'Physics' | 'Chemistry' | 'Biology' | 'Mathematics' => {
  const s = (sub || '').trim().toLowerCase();
  if (s.includes('math')) return 'Mathematics';
  if (s.includes('chem')) return 'Chemistry';
  if (s.includes('bio') || s.includes('botany') || s.includes('zoology')) return 'Biology';
  return 'Physics';
};

export const getNcertChaptersBySubject = (
  subject: string,
  classLevel?: string
): NcertChapter[] => {
  const norm = normalizeSubjectName(subject);
  const catalog = ALL_NCERT_CHAPTERS[norm] || NCERT_PHYSICS;
  if (!classLevel || classLevel === 'All' || classLevel === 'Dropper / Repeater' || classLevel === 'Dropper') {
    return catalog;
  }
  const filtered = catalog.filter((c) => c.class === classLevel);
  return filtered.length > 0 ? filtered : catalog;
};
