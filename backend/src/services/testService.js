const testRepository = require('../repositories/testRepository');
const ragService = require('./ragService');
const questionBank = require('../data/questionBank');
const logger = require('../utils/logger');

// Removes duplicate questions based on lowercase, trimmed question text
function removeDuplicateQuestions(questions) {
  if (!Array.isArray(questions)) return [];
  const seen = new Set();

  return questions.filter((question) => {
    if (!question) return false;
    const raw = question.question || question.question_text || question.text || '';
    const key = String(raw).trim().toLowerCase();

    if (!key || seen.has(key)) {
      return false;
    }

    seen.add(key);
    return true;
  });
}

// Fisher-Yates array shuffling to randomize option positions (A, B, C, D)
function shuffleArray(array) {
  if (!Array.isArray(array)) return [];
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

class TestService {
  async listTests(userId) {
    return await testRepository.getByUser(userId);
  }

  async getTest(id, userId) {
    const test = await testRepository.getById(id, userId);
    if (!test) {
      const err = new Error('Test not found or access denied.');
      err.statusCode = 404;
      err.code = 'TEST_NOT_FOUND';
      throw err;
    }
    return test;
  }

  async createTest(userId, testData) {
    const deduplicatedQuestions = removeDuplicateQuestions(testData.questions || []);
    return await testRepository.create(
      {
        user_id: userId,
        title: testData.title,
        subject: testData.subject,
        chapter: testData.chapter,
      },
      deduplicatedQuestions
    );
  }

  async generateTest(
    userId,
    {
      exam = 'NEET',
      classLevel = 'Class 12th',
      subject = 'Biology',
      subjects = null,
      chapter = 'Principles of Inheritance and Variation',
      chapters = null,
      subtopic = null,
      difficulty = 'all',
      count = 10,
      durationMinutes = null,
    } = {}
  ) {
    // Allow flexible test size: 3 up to 150 questions.
    const validCount = Math.max(3, Math.min(150, parseInt(count, 10) || 10));

    // Dynamic timer: custom duration wins; otherwise use ~1.5 minutes per question.
    const computedDuration = durationMinutes && parseInt(durationMinutes, 10) > 0
      ? parseInt(durationMinutes, 10)
      : Math.max(3, Math.round(validCount * 1.5));

    // Determine active subjects.
    let activeSubjects = [];
    if (Array.isArray(subjects) && subjects.length > 0) {
      activeSubjects = subjects.map((s) => String(s).trim()).filter(Boolean);
    } else if (typeof subjects === 'string' && subjects.includes(',')) {
      activeSubjects = subjects.split(',').map((s) => s.trim()).filter(Boolean);
    } else if (subject) {
      activeSubjects = [subject];
    } else {
      activeSubjects = ['Physics', 'Chemistry', 'Biology'];
    }

    // Main quiz questions are generated by Gemini through the RAG microservice.
    // The static question bank is intentionally no longer used for generated tests.
    const seenQuestionTexts = await testRepository.getSeenQuestionTexts(userId);

    const isMultiSubject = activeSubjects.length > 1;
    const chapterMap = typeof chapters === 'object' && chapters ? chapters : {};
    const effectiveChapters = {};

    for (const activeSubject of activeSubjects) {
      const selectedChapter = chapterMap[activeSubject] || chapterMap[activeSubject.toLowerCase()] || chapter;
      effectiveChapters[activeSubject] = selectedChapter || 'General';
    }

    let questions = [];
    const targetChapter = isMultiSubject ? 'Multi-Subject' : (effectiveChapters[activeSubjects[0]] || chapter);

    try {
      const generated = await ragService.generateQuestions({
        userId,
        exam,
        classLevel,
        subjects: activeSubjects,
        chapters: effectiveChapters,
        subtopic,
        difficulty,
        count: validCount,
        excludedQuestions: seenQuestionTexts,
      });

      const rawQuestions = Array.isArray(generated?.questions) ? generated.questions : [];
      // Normalize and validate Gemini's response: ensure exact chapter alignment and valid options/answer/explanation
      questions = rawQuestions
        .filter((q) => q && typeof q === 'object')
        .map((question) => {
          const qText = String(question.question_text || question.question || '').trim();
          const qOptions = Array.isArray(question.options)
            ? question.options.map((opt) => String(opt).trim()).filter(Boolean)
            : [];
          const qAns = String(question.correct_answer || '').trim();
          const qExpl = String(question.explanation || '').trim();
          const qSubj = question.subject || (isMultiSubject ? 'Mixed' : activeSubjects[0]);
          const qChap = question.chapter || effectiveChapters[qSubj] || targetChapter;

          // Find exact match among options
          const matchedOption = qOptions.find((opt) => opt.toLowerCase() === qAns.toLowerCase()) || qAns;

          // Ensure exactly 4 options with the correct answer included, then shuffle with Fisher-Yates
          let candidateOptions = qOptions.slice(0, 4);
          if (!candidateOptions.some((opt) => opt.toLowerCase() === matchedOption.toLowerCase())) {
            candidateOptions[0] = matchedOption;
          }
          const shuffledOptions = shuffleArray(candidateOptions);

          return {
            question_text: qText,
            options: shuffledOptions,
            correct_answer: matchedOption,
            explanation: qExpl || `Step-by-step concept derivation for ${qChap}.`,
            topic: qChap,
            subject: qSubj,
            difficulty: difficulty === 'all' ? 'medium' : difficulty,
            subtopic: subtopic || null,
          };
        })
        .filter((q) => q.question_text && q.options.length >= 4 && q.correct_answer);
    } catch (ragError) {
      logger.warn(`[TestService] Gemini question generation failed, falling back to curated curriculum question bank: ${ragError.message}`);
      if (isMultiSubject) {
        questions = questionBank.getMultiSubjectQuestions(
          activeSubjects,
          effectiveChapters,
          validCount,
          seenQuestionTexts,
          { difficulty, subtopic }
        );
      } else {
        questions = questionBank.getQuestionsForChapter(
          activeSubjects[0],
          targetChapter,
          validCount,
          seenQuestionTexts,
          { difficulty, subtopic }
        );
      }
    }

    let uniqueQuestions = removeDuplicateQuestions(questions).slice(0, validCount);

    if (uniqueQuestions.length === 0) {
      // Secondary fallback to standard subject questions if chapter had no direct match
      uniqueQuestions = questionBank.getQuestionsForChapter(
        activeSubjects[0] || 'Biology',
        'Principles of Inheritance and Variation',
        validCount,
        [],
        { difficulty }
      );
    }

    const difficultyLabel = difficulty && difficulty !== 'all' ? ` • ${difficulty.toUpperCase()}` : '';
    const subjectLabel = isMultiSubject ? activeSubjects.join(' + ') : activeSubjects[0];
    const chapterLabel = isMultiSubject ? 'Multi-Subject Challenge' : (subtopic && subtopic !== 'All Subtopics' ? `${chapter} (${subtopic})` : chapter);
    const title = `${exam} Practice: ${subjectLabel} — ${chapterLabel} (${validCount} Qs • ${computedDuration}m${difficultyLabel})`;

    const test = await testRepository.create(
      {
        user_id: userId,
        title,
        subject: subjectLabel,
        chapter: chapterLabel,
        exam,
        duration_minutes: computedDuration,
        difficulty,
        subtopic,
      },
      uniqueQuestions
    );

    // Attach metadata for the frontend
    test.duration_minutes = computedDuration;
    test.durationMinutes = computedDuration;
    test.difficulty = difficulty;
    test.subtopic = subtopic;
    test.subjects = activeSubjects;

    return test;
  }

  async deleteTest(id, userId) {
    await this.getTest(id, userId); // verify ownership
    return await testRepository.delete(id, userId);
  }
}

module.exports = new TestService();
